const ShortsStore = {
  getBookmarks() {
    try {
      const data = localStorage.getItem('ssc_bookmarks');
      return data ? JSON.parse(data) : [];
    } catch (e) {
      return [];
    }
  },

  isBookmarked(id) {
    return this.getBookmarks().includes(id);
  },

  toggleBookmark(id) {
    let list = this.getBookmarks();
    const idx = list.indexOf(id);
    let state = false;
    if (idx >= 0) {
      list.splice(idx, 1);
      state = false;
    } else {
      list.push(id);
      state = true;
    }
    localStorage.setItem('ssc_bookmarks', JSON.stringify(list));
    return state;
  },

  getCustomShorts() {
    try {
      const data = localStorage.getItem('ssc_custom_shorts');
      return data ? JSON.parse(data) : [];
    } catch (e) {
      return [];
    }
  },

  saveCustomShort(shortObj) {
    const custom = this.getCustomShorts();
    custom.unshift(shortObj);
    localStorage.setItem('ssc_custom_shorts', JSON.stringify(custom));
  },

  // Get Infinite Shuffled Stream for any Category
  getAllShorts() {
    const custom = this.getCustomShorts();
    return [...custom, ...SSC_SHORTS_POOL];
  },

  getRandomStream(category = 'all') {
    const custom = this.getCustomShorts();
    let base = [...custom, ...SSC_SHORTS_POOL];

    if (category === 'saved') {
      const bms = this.getBookmarks();
      base = base.filter(s => bms.includes(s.id));
      return base;
    }

    if (category !== 'all') {
      base = base.filter(s => s.category === category);
    }

    // Fisher-Yates Shuffle for pure randomness
    const shuffled = [...base];
    for (let i = shuffled.length - 1; i > 0; i--) {
      const j = Math.floor(Math.random() * (i + 1));
      [shuffled[i], shuffled[j]] = [shuffled[j], shuffled[i]];
    }

    return shuffled;
  }
};
